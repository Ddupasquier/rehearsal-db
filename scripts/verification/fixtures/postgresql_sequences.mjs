/** Installed private-compiler edge proof; not independent public SDK conformance. */
import assert from "node:assert/strict";
import { join } from "node:path";
import { pathToFileURL } from "node:url";
import {
  assertLocalDockerContext,
  scopedDockerEnvironment,
} from "../../../dist/src/runtime/local_docker_context.mjs";
import { runScenarioCommand } from "../scenarios/process.mjs";

export async function provePostgresqlRestoreSequences({ cwd, projectId }) {
  const local = assertLocalDockerContext({
    cwd,
    inheritedEnvironment: process.env,
  });
  const environment = scopedDockerEnvironment();
  const docker = (args, input) =>
    runScenarioCommand("docker", ["--host", local.endpoint, ...args], {
      cwd,
      environment,
      input,
      timeout: 30000,
      maxBuffer: 65536,
    });
  const daemon = docker(["info", "--format", "{{.ID}}"]).trim();
  assert.match(daemon, /^[a-zA-Z0-9:_-]{1,256}$/u);
  const id = docker([
    "ps",
    "--no-trunc",
    "--filter",
    `label=com.rehearsal-db.project=${projectId}`,
    "--format",
    "{{.ID}}",
  ]).trim();
  assert.match(id, /^[a-f0-9]{64}$/u);
  const observe = () => {
    const fields = docker([
      "inspect",
      "--format",
      '{{.Id}}\n{{.Image}}\n{{.State.StartedAt}}\n{{.State.Running}}\n{{index .Config.Labels "com.rehearsal-db.project"}}',
      id,
    ])
      .trim()
      .split(/\r?\n/u);
    assert.equal(fields.length, 5);
    assert.equal(fields[0], id);
    assert.match(fields[1], /^sha256:[a-f0-9]{64}$/u);
    assert.ok(fields[2].length <= 64 && Number.isFinite(Date.parse(fields[2])));
    assert.equal(fields[3], "true");
    assert.equal(fields[4], projectId);
    return JSON.stringify(fields);
  };
  const identity = observe();
  const compiler = await import(
    pathToFileURL(
      join(cwd, "node_modules/@rehearsal-db/core/dist/src/runtime/restore.mjs"),
    ).href
  );
  const cases = [
    ["serial_positive", "id serial primary key", [10, 20], 21, "NO"],
    ["serial_below_minimum", "id serial primary key", [-2, -1], 1, "NO"],
    [
      "identity_below_minimum",
      "id integer generated by default as identity primary key",
      [-2, -1],
      1,
      "YES",
    ],
    [
      "identity_positive",
      "id integer generated by default as identity (start with 5 increment by 5) primary key",
      [10, 20],
      25,
      "YES",
    ],
    ["serial_negative", "id serial primary key", [-10, -20], -21, "NO"],
    ["serial_above_maximum", "id serial primary key", [1, 2], -1, "NO"],
    [
      "identity_above_maximum",
      "id integer generated by default as identity (increment by -1) primary key",
      [1, 2],
      -1,
      "YES",
    ],
    [
      "identity_negative",
      "id integer generated by default as identity (start with -5 increment by -5 minvalue -2147483648 maxvalue -1) primary key",
      [-10, -20],
      -25,
      "YES",
    ],
    ["serial_empty", "id serial primary key", [], 71, "NO"],
    [
      "identity_empty",
      "id integer generated by default as identity (start with 81 increment by 3) primary key",
      [],
      81,
      "YES",
    ],
    [
      "uuid_plain",
      "id uuid primary key default '11111111-1111-4111-8111-111111111111'::uuid",
      ["22222222-2222-4222-8222-222222222222"],
      "11111111-1111-4111-8111-111111111111",
      "NO",
    ],
  ];
  const manifest = {
    tables: cases.map(([name, , , , identity]) => ({
      schema: "pg_temp",
      name,
      sourceRows: "STREAM AND SANITIZE",
      columns: [
        {
          name: "id",
          action: "KEEP EXACTLY",
          generated: "NEVER",
          identity,
          foreignKey: null,
        },
      ],
    })),
  };
  const setup =
    cases
      .map(
        ([name, definition]) =>
          `create temporary table ${name} (${definition});`,
      )
      .join("\n") +
    `
alter sequence pg_temp.serial_negative_id_seq increment by -1 minvalue -2147483648 maxvalue -1 start with -1 restart with -1;
alter sequence pg_temp.serial_above_maximum_id_seq increment by -1 minvalue -2147483648 maxvalue -1 start with -1 restart with -1;
alter sequence pg_temp.serial_empty_id_seq start with 71 restart with 71;
`;
  const rows = cases.flatMap(([table, , values]) =>
    values.map((id) =>
      compiler.encodeBaselineRecordForCopy(
        JSON.stringify({ schema: "pg_temp", table, row: { id } }),
      ),
    ),
  );
  const suffix = compiler.buildRestoreSqlSuffix({
    manifest,
    tableCounts: Object.fromEntries(
      cases.map(([name, , values]) => [`pg_temp.${name}`, values.length]),
    ),
    restoreSupabaseAuth: false,
  });
  const checks = cases
    .map(
      ([name, , , expected]) =>
        `do $proof$ declare actual text; begin insert into pg_temp.${name} default values returning id::text into actual; if actual is distinct from '${expected}' then raise exception 'Installed restore sequence proof failed: ${name}'; end if; end $proof$;`,
    )
    .join("\n");
  const refusalMessage =
    "Rehearsal cannot advance the owned sequence beyond restored IDs within its configured bounds";
  const refusals = [
    ["serial_past_maximum", "maxvalue 50", 100],
    [
      "serial_past_minimum",
      "increment by -1 minvalue -50 maxvalue -1 start with -1 restart with -1",
      -100,
    ],
  ].map(([name, sequenceOptions, value]) => {
    const refusalSuffix = compiler.buildRestoreSqlSuffix({
      manifest: {
        tables: [{ ...manifest.tables[0], name }],
      },
      tableCounts: { [`pg_temp.${name}`]: 1 },
      restoreSupabaseAuth: false,
    });
    const blocks = refusalSuffix.match(
      /do \$rehearsal_sequence\$\n[\s\S]*?\n\$rehearsal_sequence\$;/gu,
    );
    assert.equal(blocks?.length, 1);
    // Execute the installed compiler's actual sequence block. Catch only its
    // fixed range refusal; no copied implementation or persistent objects.
    const blockLiteral = `'${blocks[0].replaceAll("'", "''")}'`;
    return `create temporary table ${name} (id serial primary key);
alter sequence pg_temp.${name}_id_seq ${sequenceOptions};
insert into pg_temp.${name} (id) values (${value});
do $range_proof$ begin
  begin
    execute ${blockLiteral};
  exception when raise_exception then
    if sqlerrm = '${refusalMessage}' then return; end if;
    raise;
  end;
  raise exception 'Installed restore failed to refuse exhausted sequence bounds';
end $range_proof$;`;
  });
  const count = cases.length + refusals.length;
  const marker = `installed-private-restore-sequences:${count}`;
  const sql = `\\set ON_ERROR_STOP on\n${setup}\n${compiler.buildRestoreSqlPrefix()}${rows.join("\n")}\n${suffix}\n${checks}\n${refusals.join("\n")}\nselect '${marker}';\n`;
  assert.ok(Buffer.byteLength(sql) < 65536);
  assert.equal(observe(), identity);
  assert.equal(docker(["info", "--format", "{{.ID}}"]).trim(), daemon);
  const output = docker(
    [
      "exec",
      "--interactive",
      id,
      "psql",
      "--no-psqlrc",
      "--quiet",
      "--no-align",
      "--tuples-only",
      "--username",
      "postgres",
      "--dbname",
      "postgres",
    ],
    sql,
  );
  assert.ok(output.split(/\r?\n/u).includes(marker));
  assert.equal(observe(), identity);
  return {
    status: "passed",
    cases: count,
    restoredDefaultInserts: cases.length,
    configuredRangeRefusals: refusals.length,
    scope: "installed-private-restore-compiler-temporary-objects",
    persistentObjectsCreated: false,
  };
}
