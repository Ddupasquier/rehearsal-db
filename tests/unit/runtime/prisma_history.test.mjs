import { createHash } from "node:crypto";
import {
  mkdtemp,
  mkdir,
  writeFile,
  rm,
  symlink,
  rename,
  truncate,
} from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { pathToFileURL } from "node:url";
import { afterEach, expect, it } from "vitest";
import {
  readPrismaMigrationInventory,
  normalizePrismaMigrationLedger,
  verifyPrismaMigrationLedger,
  PRISMA_HISTORY_LIMITS,
} from "../../../dist/src/runtime/prisma_history.mjs";
const roots = [];
const hash = (bytes) => createHash("sha256").update(bytes).digest("hex");
const names = ["20260101000000_init", "20260201000000_add_widgets"];
const lock =
  '# Please do not edit this file manually\nprovider = "postgresql"\n';
async function fixture() {
  const root = await mkdtemp(join(tmpdir(), "prisma-history-"));
  roots.push(root);
  await writeFile(join(root, "migration_lock.toml"), lock);
  for (const folder of [...names].reverse()) {
    await mkdir(join(root, folder));
    await writeFile(
      join(root, folder, "migration.sql"),
      Buffer.from("-- raw CRLF\r\nselect 1;\r\n"),
    );
  }
  return { root, url: pathToFileURL(root + "/") };
}
afterEach(async () => {
  for (const root of roots.splice(0))
    await rm(root, { recursive: true, force: true });
});
const ledger = (entries) =>
  entries.map((e) => ({
    migration_name: `${e.version}_${e.name}`,
    checksum: e.fileSha256,
    finished_at: "2026-02-01T00:00:00.000Z",
    rolled_back_at: null,
  }));
it("preserves native paths, raw CRLF hashes, ordered entries and exact provider lock binding", async () => {
  const { url } = await fixture();
  const seen = [];
  const result = await readPrismaMigrationInventory(url, {
    readBytes: async (path, filename) => {
      seen.push(filename);
      return (await import("node:fs/promises")).readFile(path);
    },
  });
  expect(result.entries).toEqual(
    names.map((folder) => ({
      version: folder.slice(0, 14),
      name: folder.slice(15),
      filename: `${folder}/migration.sql`,
      fileSha256: hash(Buffer.from("-- raw CRLF\r\nselect 1;\r\n")),
    })),
  );
  expect(result.binding).toEqual({
    schemaVersion: 1,
    kind: "prisma",
    version: "7.10.1",
    provider: "postgresql",
    lockSha256: hash(lock),
  });
  expect(seen).toEqual([
    "migration_lock.toml",
    ...names.map((folder) => `${folder}/migration.sql`),
  ]);
  expect(result.entries[0].fileSha256).not.toBe(
    hash("-- raw CRLF\nselect 1;\n"),
  );
});
it.each([
  "missing-lock",
  "wrong-provider",
  "duplicate-provider",
  "extra-lock-key",
  "mismatched-quote",
  "malformed-folder",
  "duplicate-version",
  "extra-top-file",
  "extra-child",
  "missing-sql",
  "symlink-sql",
  "symlink-folder",
  "symlink-root",
])("refuses %s without executing anything", async (kind) => {
  const { root, url } = await fixture();
  let selected = url;
  if (kind === "missing-lock") await rm(join(root, "migration_lock.toml"));
  if (kind === "wrong-provider")
    await writeFile(join(root, "migration_lock.toml"), 'provider = "mysql"\n');
  if (kind === "duplicate-provider")
    await writeFile(join(root, "migration_lock.toml"), lock + lock);
  if (kind === "extra-lock-key")
    await writeFile(
      join(root, "migration_lock.toml"),
      lock + 'secret = "must-not-be-read-as-config"\n',
    );
  if (kind === "mismatched-quote")
    await writeFile(
      join(root, "migration_lock.toml"),
      `provider = "postgresql'\n`,
    );
  if (kind === "malformed-folder") await mkdir(join(root, "migration_init"));
  if (kind === "duplicate-version") {
    await mkdir(join(root, "20260101000000_other"));
    await writeFile(
      join(root, "20260101000000_other/migration.sql"),
      "select 1;",
    );
  }
  if (kind === "extra-top-file")
    await writeFile(join(root, "schema.prisma"), "must-not-evaluate");
  if (kind === "extra-child")
    await writeFile(join(root, names[0], "extra.sql"), "must-not-execute");
  if (kind === "missing-sql") await rm(join(root, names[0], "migration.sql"));
  if (kind === "symlink-sql") {
    await rm(join(root, names[0], "migration.sql"));
    await symlink(
      join(root, names[1], "migration.sql"),
      join(root, names[0], "migration.sql"),
    );
  }
  if (kind === "symlink-folder") {
    await rm(join(root, names[0]), { recursive: true });
    await symlink(join(root, names[1]), join(root, names[0]));
  }
  if (kind === "symlink-root") {
    const alias = root + "-alias";
    roots.push(alias);
    await symlink(root, alias);
    selected = pathToFileURL(alias + "/");
  }
  await expect(readPrismaMigrationInventory(selected)).rejects.toThrow();
});
it("refuses files beyond the byte bound before reading sparse contents", async () => {
  const { root, url } = await fixture();
  await truncate(
    join(root, names[0], "migration.sql"),
    PRISMA_HISTORY_LIMITS.maximumFileBytes + 1,
  );
  await expect(readPrismaMigrationInventory(url)).rejects.toThrow();
});
it("refuses callback byte substitution and concurrent leaf replacement", async () => {
  const { root, url } = await fixture();
  await expect(
    readPrismaMigrationInventory(url, {
      readBytes: async () => Buffer.from("different"),
    }),
  ).rejects.toThrow();
  await expect(
    readPrismaMigrationInventory(url, {
      readBytes: async (path, filename) => {
        const { readFile } = await import("node:fs/promises");
        const bytes = await readFile(path);
        if (filename.endsWith("migration.sql")) {
          await rename(join(root, filename), join(root, filename + ".old"));
          await writeFile(join(root, filename), bytes);
        }
        return bytes;
      },
    }),
  ).rejects.toThrow();
});
it("accepts a complete ledger or an exact successful prefix, retaining native names/checksums", async () => {
  const { url } = await fixture();
  const { entries } = await readPrismaMigrationInventory(url);
  const rows = ledger(entries);
  expect(verifyPrismaMigrationLedger({ rows, entries })).toEqual(rows);
  expect(
    verifyPrismaMigrationLedger({ rows: rows.slice(0, 1), entries }),
  ).toEqual(rows.slice(0, 1));
});
it.each([
  "missing",
  "duplicate",
  "failed",
  "rolled-back",
  "checksum",
  "gap",
  "unordered",
  "foreign",
  "unknown-column",
  "bad-time",
  "missing-column",
])("rejects %s Prisma ledger history", async (kind) => {
  const { url } = await fixture();
  const { entries } = await readPrismaMigrationInventory(url);
  let rows = ledger(entries);
  if (kind === "missing") rows = [];
  if (kind === "duplicate") rows = [rows[0], rows[0]];
  if (kind === "failed") rows[0].finished_at = null;
  if (kind === "rolled-back") rows[0].rolled_back_at = "2026-02-01T00:00:00Z";
  if (kind === "checksum") rows[0].checksum = "f".repeat(64);
  if (kind === "gap") rows = rows.slice(1);
  if (kind === "unordered") rows.reverse();
  if (kind === "foreign") rows[0].migration_name = "20260101000000_foreign";
  if (kind === "unknown-column") rows[0].logs = "private-output";
  if (kind === "bad-time") rows[0].finished_at = "not-a-date";
  if (kind === "missing-column") delete rows[0].rolled_back_at;
  expect(() => verifyPrismaMigrationLedger({ rows, entries })).toThrow(
    /unavailable, malformed, unsafe or divergent/,
  );
});
it("bounds native ledger rows and validates independently supplied inventory", async () => {
  expect(() =>
    normalizePrismaMigrationLedger(
      new Array(PRISMA_HISTORY_LIMITS.maximumFiles + 1).fill({}),
    ),
  ).toThrow();
  const { url } = await fixture();
  const { entries } = await readPrismaMigrationInventory(url);
  const rows = ledger(entries);
  expect(() =>
    verifyPrismaMigrationLedger({ rows, entries: [...entries].reverse() }),
  ).toThrow();
  expect(() =>
    verifyPrismaMigrationLedger({
      rows,
      entries: entries.map((e) => ({
        ...e,
        filename: e.filename.replace("/migration.sql", ".sql"),
      })),
    }),
  ).toThrow();
});
